"""粤语注音引擎（Jyutping）—— lyric-writing 的共用底座

优先级（高 → 低）：
  ① OVERRIDES    人工按语境钉死的多音字（最高优先；调用方会明确列出哪些字被覆盖）
  ② S2T（简→繁）→ pycantonese    —— **简体字走这条**
  ③ pycantonese 直接注音          —— 繁体字走这条
  ④ 仍失败 → 返回 None，由调用方报「缺字」，**不静默跳过**

★ **简体字必须先转繁再注音**，不能让库直读：简体字常命中「另一个同形字」的读音。
  实例：「听」库直读 jan5（那是另一个字），正字「聽」才是 ting3。

★ 声调是 Jyutping 的**六调制**：1 阴平 / 2 阴上 / 3 阴去 / 4 阳平 / 5 阳上 / 6 阳去
  **入声不另设调号**（-p/-t/-k 韵尾才是入声标志）。
  所以「入声」绝不能用 tone >= 7 判定 —— 六调制里没有 7/8/9，那样写永远不会触发。
"""

INITIALS = ["ng", "gw", "kw",
            "b", "p", "m", "f", "d", "t", "n", "l",
            "g", "k", "h", "w", "z", "c", "s", "j"]

FLAT_TONES = {1, 3, 4, 6}
RISING_TONES = {2, 5}
CHECKED_CODAS = ("p", "t", "k")

CHECKED_CHARS = {"唔", "嘅", "咗", "係", "冇", "咁", "喺", "佢", "哋", "睇", "嘢", "俾"}


def split_jyutping(jp):
    """'gwaan1' -> ('gw', 'aan', 1)；'uk1' -> ('', 'uk', 1)"""
    tone = int(jp[-1]) if jp and jp[-1].isdigit() else None
    core = jp[:-1] if tone is not None else jp
    for ini in INITIALS:
        if core.startswith(ini):
            return ini, core[len(ini):], tone
    return "", core, tone


def is_checked(final):
    """入声：韵尾 -p / -t / -k"""
    return final.endswith(CHECKED_CODAS)


