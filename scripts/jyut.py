class JyutEngine:
    """统一注音入口。查不到就返回 None，由调用方决定怎么报。"""

    def __init__(self, overrides=None, extra_s2t=None, use_lib=True):
        self.overrides = dict(OVERRIDES)
        if overrides:
            self.overrides.update(overrides)
        self.s2t = dict(S2T)
        if extra_s2t:
            self.s2t.update(extra_s2t)
        self.use_lib = use_lib
        self._raw = None
        if use_lib:
            try:
                import pycantonese
                self._raw = pycantonese.characters_to_jyutping
            except Exception:
                self.use_lib = False
        self._cache = {}
        self.source = {}

    def _lib_lookup(self, ch):
        if not self._raw:
            return None
        try:
            res = self._raw(ch)
        except Exception:
            return None
        if not res:
            return None
        _c, jp = res[0]
        if not jp:
            return None
        return split_jyutping(jp)

    def lookup(self, ch):
        """-> (full, final, tone, source) 或 None

        ★ 简体字**必须先经 S2T 转繁**再交给库，不能直接让库注音——
          简体字很容易命中「另一个同形字」的读音（实例：「听」库直读 jan5，
          那是另一个字；正字「聽」才是 ting3）。
        """
        if ch in self._cache:
            return self._cache[ch]
        out = None
        t = self.s2t.get(ch, ch)
        # ① 人工覆盖（原字或转换后的字，两条都查：「着」→「著」→ zoek6）
        for k in (t, ch):
            if k in self.overrides:
                ini, fin, tone = split_jyutping(self.overrides[k])
                out = (ini + fin, fin, tone, "override")
                break
        # ② 转繁后查库；转不动就直查
        if out is None:
            r = self._lib_lookup(t)
            if r:
                out = (r[0] + r[1], r[1], r[2], "s2t" if t != ch else "lib")
            elif t != ch:
                r = self._lib_lookup(ch)
                if r:
                    out = (r[0] + r[1], r[1], r[2], "lib")
        self._cache[ch] = out
        if out:
            self.source[ch] = out[3]
        return out

    def tone_of(self, ch):
        r = self.lookup(ch)
        return r[2] if r else None

    def final_of(self, ch):
        r = self.lookup(ch)
        return r[1] if r else None

    def missing(self, text):
        """只对非空白字符报缺字（换行/全角空格不算字）"""
        return [c for c in text if not c.isspace() and self.lookup(c) is None]

    def override_hits(self):
        return sorted(c for c, s in self.source.items() if s == "override")

    def s2t_hits(self):
        return sorted(c for c, s in self.source.items() if s == "s2t")

    def audit_table(self):
        """自检 S2T 表：目标字必须能被库注音，否则这张映射是坏的。"""
        bad = []
        for k, v in self.s2t.items():
            if self._lib_lookup(v) is None:
                bad.append((k, v))
        return bad

    def audit_necessity(self):
        """列出「库本来能读、却被 S2T 改掉读音」的条目 —— 这批必须人工确认。

        直读就「库不认」的不算风险（映射纯属必要）；
        真正危险的是简体字**本身有读音**、却被改掉的那些：万一改的方向错了，
        就会静默用错音（实例：「表」库直读 biu2 是对的，我却把它映射到「錶」biu1）。
        返回值：{字: (直读音, 采用音, 来源)}
        """
        need = {}
        for k in self.s2t:
            a = self._lib_lookup(k)
            b = self.lookup(k)
            if not a or not b:
                continue
            if (a[1], a[2]) == (b[1], b[2]):
                continue
            need[k] = (a[1] + str(a[2]), b[1] + str(b[2]), b[3])
        return need

    # 库「只有一个读音」但实际多音的常用繁体字 —— 落到这些字要人工确认
    MULTI_READING = "長 種 當 重 行 樂 好 為 中 相 數 分 應 間 教 落 著 過 會"
